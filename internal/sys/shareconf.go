package sys

import (
	"fmt"
	"sort"
	"strings"
)

// ShareSpec describes one share to the system layer. It is deliberately
// structured data, not config text: the system layer (and the root agent)
// builds the Samba config itself, so a caller can only ever ask for shares
// that pass the rules in rules.go.
type ShareSpec struct {
	Name    string `json:"name"`
	Path    string `json:"path"`
	Comment string `json:"comment,omitempty"`
	// Readers may connect; Writers (a subset) may also change files. Both
	// hold account names of users that still have SMB access.
	Readers []string `json:"readers,omitempty"`
	Writers []string `json:"writers,omitempty"`
}

// ConfigHeader starts every managed config file.
const ConfigHeader = `# Managed by NetShare Hub. Do not edit this file: it is rewritten
# every time a share changes. Manage shares in the web UI instead.
`

// RenderShares produces the whole managed Samba config. It checks every
// value and refuses to produce a config from anything that is not safe.
func RenderShares(shares []ShareSpec) (string, error) {
	shares = append([]ShareSpec(nil), shares...) // do not reorder the caller's slice
	sort.Slice(shares, func(i, j int) bool { return strings.ToLower(shares[i].Name) < strings.ToLower(shares[j].Name) })

	var b strings.Builder
	b.WriteString(ConfigHeader)

	for _, s := range shares {
		if !ValidShareName(s.Name) {
			return "", fmt.Errorf("refusing to render share with unsafe name %q", s.Name)
		}
		if !ValidSharePath(s.Path) || !SharablePath(s.Path) {
			return "", fmt.Errorf("refusing to render share %q with unsafe path %q", s.Name, s.Path)
		}
		if !ValidShareComment(s.Comment) {
			return "", fmt.Errorf("refusing to render share %q with unsafe comment", s.Name)
		}
		for _, name := range append(append([]string{}, s.Readers...), s.Writers...) {
			if !ValidAccountName(name) {
				return "", fmt.Errorf("refusing to render share %q with unsafe account name %q", s.Name, name)
			}
		}

		fmt.Fprintf(&b, "\n[%s]\n", s.Name)
		param(&b, "path", s.Path)
		if s.Comment != "" {
			param(&b, "comment", s.Comment)
		}
		param(&b, "browseable", "yes")
		param(&b, "guest ok", "no")

		if len(s.Readers) == 0 {
			// IMPORTANT: an empty "valid users" means EVERY user may connect.
			// A share nobody was given access to must be switched off instead.
			param(&b, "available", "no")
			continue
		}

		// Everyone is read-only unless listed in "write list".
		param(&b, "read only", "yes")
		param(&b, "valid users", strings.Join(s.Readers, ", "))
		if len(s.Writers) > 0 {
			param(&b, "write list", strings.Join(s.Writers, ", "))
		}
		// Files created over SMB belong to the shared group, so every user
		// with write access can work with files made by the others.
		param(&b, "force group", ManagedGroup)
		param(&b, "create mask", "0660")
		param(&b, "directory mask", "2770")
	}
	return b.String(), nil
}

func param(b *strings.Builder, key, value string) {
	fmt.Fprintf(b, "   %s = %s\n", key, value)
}

// ParseShares reads back a config produced by RenderShares. The managed
// config file is the single record of which shares are live and who may use
// them, so the system layer reads it (instead of keeping a second copy that
// could drift) when it decides what a user's file worker may reach.
//
// It only understands the exact format RenderShares writes.
func ParseShares(config string) []ShareSpec {
	var shares []ShareSpec
	var current *ShareSpec
	available := true

	flush := func() {
		if current == nil {
			return
		}
		if !available {
			// A share that is switched off is reachable by nobody.
			current.Readers, current.Writers = nil, nil
		}
		shares = append(shares, *current)
		current, available = nil, true
	}

	for _, line := range strings.Split(config, "\n") {
		line = strings.TrimSpace(line)
		switch {
		case line == "" || strings.HasPrefix(line, "#"):
			continue
		case strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]"):
			flush()
			current = &ShareSpec{Name: line[1 : len(line)-1]}
			continue
		}
		key, value, ok := strings.Cut(line, " = ")
		if !ok || current == nil {
			continue
		}
		switch key {
		case "path":
			current.Path = value
		case "comment":
			current.Comment = value
		case "valid users":
			current.Readers = strings.Split(value, ", ")
		case "write list":
			current.Writers = strings.Split(value, ", ")
		case "available":
			available = value != "no"
		}
	}
	flush()
	return shares
}
