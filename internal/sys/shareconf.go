package sys

import (
	"fmt"
	"slices"
	"sort"
	"strings"
)

// ShareSpec describes one share to the system layer. It is deliberately
// structured data, not config text: the system layer (and the root agent)
// builds the Samba config and the folder's permissions itself, so a caller
// can only ever ask for shares that pass the rules in rules.go.
//
// The lists hold account names of managed users that may use the share. They
// are already the EFFECTIVE access (a read-only share has no writers): the
// system layer applies them as given, to Samba and to the folder's ACL.
type ShareSpec struct {
	Name    string `json:"name"`
	Path    string `json:"path"`
	Comment string `json:"comment,omitempty"`
	// Readers may open and read files. Writers are the readers that may
	// also change files (Writers is a subset of Readers).
	Readers []string `json:"readers,omitempty"`
	Writers []string `json:"writers,omitempty"`
	// Uploaders may add files to the top folder but cannot see what is in
	// it (a "drop box"). They are never readers.
	Uploaders []string `json:"uploaders,omitempty"`
	// Guest lets anyone on the network read the share without a password,
	// and every managed user read it with theirs. Guests never write.
	Guest bool `json:"guest,omitempty"`
	// HideUnreadable hides files and folders a user cannot read (over SMB
	// and in the file manager). It slows down listing very big folders.
	HideUnreadable bool `json:"hideUnreadable,omitempty"`
}

// Live reports whether anyone at all may use the share.
func (s ShareSpec) Live() bool {
	return s.Guest || len(s.Readers) > 0 || len(s.Uploaders) > 0
}

// Check validates every value of a share. RenderShares and the permission
// code both rely on it, so nothing unchecked reaches Samba or the filesystem.
func (s ShareSpec) Check() error {
	if !ValidShareName(s.Name) {
		return fmt.Errorf("unsafe share name %q", s.Name)
	}
	if !ValidSharePath(s.Path) || !SharablePath(s.Path) {
		return fmt.Errorf("share %q: unsafe path %q", s.Name, s.Path)
	}
	if !ValidShareComment(s.Comment) {
		return fmt.Errorf("share %q: unsafe comment", s.Name)
	}
	for _, list := range [][]string{s.Readers, s.Writers, s.Uploaders} {
		for _, name := range list {
			if !ValidAccountName(name) {
				return fmt.Errorf("share %q: unsafe account name %q", s.Name, name)
			}
		}
	}
	for _, name := range s.Writers {
		if !slices.Contains(s.Readers, name) {
			return fmt.Errorf("share %q: writer %q is not a reader", s.Name, name)
		}
	}
	for _, name := range s.Uploaders {
		if slices.Contains(s.Readers, name) {
			return fmt.Errorf("share %q: %q is both an uploader and a reader", s.Name, name)
		}
	}
	// Everyone reads a guest share, uploads included: "upload only" would
	// promise a privacy it cannot keep.
	if s.Guest && len(s.Uploaders) > 0 {
		return fmt.Errorf("share %q: a guest share cannot have upload-only users", s.Name)
	}
	return nil
}

// ConfigHeader starts every managed config file.
const ConfigHeader = `# Managed by NetShare Hub. Do not edit this file: it is rewritten
# every time a share changes. Manage shares in the web UI instead.
`

// uploadOnlyKey records the drop-box users in the config, so ParseShares can
// tell them from writers (in Samba both are just in "write list").
const uploadOnlyKey = "# upload only:"

// RenderShares produces the whole managed Samba config. It checks every
// value and refuses to produce a config from anything that is not safe.
//
// How access maps to Samba (the folder's ACL, set by the system layer,
// enforces the same thing in the kernel):
//
//	readers    valid users
//	writers    valid users + write list
//	uploaders  valid users + write list (the ACL stops them listing)
//	guest      guest ok = yes, and no valid users: anyone may read
func RenderShares(shares []ShareSpec) (string, error) {
	shares = append([]ShareSpec(nil), shares...) // do not reorder the caller's slice
	sort.Slice(shares, func(i, j int) bool { return strings.ToLower(shares[i].Name) < strings.ToLower(shares[j].Name) })

	var b strings.Builder
	b.WriteString(ConfigHeader)

	for _, s := range shares {
		if err := s.Check(); err != nil {
			return "", fmt.Errorf("refusing to render: %w", err)
		}

		fmt.Fprintf(&b, "\n[%s]\n", s.Name)
		param(&b, "path", s.Path)
		if s.Comment != "" {
			param(&b, "comment", s.Comment)
		}
		param(&b, "browseable", "yes")
		param(&b, "guest ok", yesNo(s.Guest))

		if !s.Live() {
			// IMPORTANT: an empty "valid users" means EVERY user may connect.
			// A share nobody was given access to must be switched off instead.
			param(&b, "available", "no")
			continue
		}

		// Everyone is read-only unless listed in "write list".
		param(&b, "read only", "yes")
		if !s.Guest {
			param(&b, "valid users", strings.Join(append(append([]string{}, s.Readers...), s.Uploaders...), ", "))
		}
		if writers := append(append([]string{}, s.Writers...), s.Uploaders...); len(writers) > 0 {
			param(&b, "write list", strings.Join(writers, ", "))
		}
		if len(s.Uploaders) > 0 {
			fmt.Fprintf(&b, "   %s %s\n", uploadOnlyKey, strings.Join(s.Uploaders, ", "))
		}
		// Users only see (in the share list) shares they may open, and, when
		// asked, only the files and folders they may read.
		param(&b, "access based share enum", "yes")
		if s.HideUnreadable {
			param(&b, "hide unreadable", "yes")
		}
		// New files and folders take the folder's default ACL (so everyone
		// with access keeps it), and the masks keep that ACL from being cut
		// down: "rw" for files, "rwx" for folders, nothing for others.
		param(&b, "inherit acls", "yes")
		param(&b, "create mask", "0660")
		param(&b, "directory mask", "0770")
	}
	return b.String(), nil
}

func param(b *strings.Builder, key, value string) {
	fmt.Fprintf(b, "   %s = %s\n", key, value)
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

// ParseShares reads back a config produced by RenderShares. The managed
// config file is the single record of which shares are live and who may use
// them, so the system layer reads it (instead of keeping a second copy that
// could drift) when it decides what a user's file worker may reach.
//
// It only understands the exact format RenderShares writes.
func ParseShares(config string) []ShareSpec {
	var shares []ShareSpec
	var current *ShareSpec
	available := true
	var writeList []string

	flush := func() {
		if current == nil {
			return
		}
		// "write list" holds writers and uploaders.
		for _, name := range writeList {
			if !slices.Contains(current.Uploaders, name) {
				current.Writers = append(current.Writers, name)
			}
		}
		// "valid users" holds readers and uploaders.
		current.Readers = slices.DeleteFunc(current.Readers, func(n string) bool { return slices.Contains(current.Uploaders, n) })
		if current.Guest {
			// A guest share has no "valid users" (everyone may read), so the
			// named readers are not recorded; writers are always readers.
			current.Readers = append(current.Readers, current.Writers...)
		}
		if len(current.Readers) == 0 {
			current.Readers = nil
		}
		if !available {
			// A share that is switched off is reachable by nobody.
			current.Readers, current.Writers, current.Uploaders, current.Guest = nil, nil, nil, false
		}
		shares = append(shares, *current)
		current, available, writeList = nil, true, nil
	}

	for _, line := range strings.Split(config, "\n") {
		line = strings.TrimSpace(line)
		if rest, ok := strings.CutPrefix(line, uploadOnlyKey); ok && current != nil {
			current.Uploaders = strings.Split(strings.TrimSpace(rest), ", ")
			continue
		}
		switch {
		case line == "" || strings.HasPrefix(line, "#"):
			continue
		case strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]"):
			flush()
			current = &ShareSpec{Name: line[1 : len(line)-1]}
			continue
		}
		key, value, ok := strings.Cut(line, " = ")
		if !ok || current == nil {
			continue
		}
		switch key {
		case "path":
			current.Path = value
		case "comment":
			current.Comment = value
		case "valid users":
			current.Readers = strings.Split(value, ", ")
		case "write list":
			writeList = strings.Split(value, ", ")
		case "guest ok":
			current.Guest = value == "yes"
		case "hide unreadable":
			current.HideUnreadable = value == "yes"
		case "available":
			available = value != "no"
		}
	}
	flush()
	return shares
}
